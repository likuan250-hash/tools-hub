async function fetchBiliTop() {
  const r = await fetch("https://api.bilibili.com/x/web-interface/ranking/v2?rid=4&type=all", {
    headers: {
      "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36",
      Referer: "https://www.bilibili.com/",
    },
  });
  const j = await r.json();
  return ((j.data && j.data.list) || []).map((x) => ({
    title: x.title || "",
    play: Number((x.stat && x.stat.view) || 0),
  }));
}

async function main() {
  const bili = await fetchBiliTop();
  const seen = new Set();
  const steam = [];
  for (const name of STEAM_TOP) {
    const k = String(name)
      .toLowerCase()
      .replace(/[^a-z0-9\u4e00-\u9fff]/g, "");
    if (!k || seen.has(k)) continue;
    seen.add(k);
    steam.push({ rank: steam.length + 1, name });
  }
  fs.writeFileSync(
    OUT,
    JSON.stringify({ generatedAt: new Date().toISOString(), steam, bili }, null, 2),
    "utf8",
  );
  console.log("Steam:", steam.length, "条; B站:", bili.length, "条");
  console.log("输出:", OUT);
}

main().catch((e) => {
  console.error("ERR", e.message);
  process.exit(1);
});
